// 1. GENERADOR DE TEMPORADAS INDIVIDUALES E INTERCALADAS
// ============================================================================
export function buildSingleSeason(seasonNumber, count, year, arc, titles = null) {
    const episodes = [];
    for (let e = 1; e <= count; e++) {
        const customTitle = titles && titles[e - 1]
            ? titles[e - 1]
            : `Episodio ${e}${arc ? ' — ' + arc : ''}`;
        episodes.push({
            code: `S${seasonNumber}E${e}`,
            num: e,
            title: customTitle
        });
    }
    return [{
        seasonNumber,
        year,
        note: arc || '',
        episodes
    }];
}

